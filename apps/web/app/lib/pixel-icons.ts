/** 把点阵合并成每种颜色一条 path（按行合并连续像素，减少节点数）。 */
export function iconPaths(rows: readonly string[]): { main: string; sub: string } {
  let main = "";
  let sub = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      if (c !== "#" && c !== "o") {
        x++;
        continue;
      }
      let w = 1;
      while (row[x + w] === c) w++;
      const seg = `M${x} ${y}h${w}v1h-${w}z`;
      if (c === "#") main += seg;
      else sub += seg;
      x += w;
    }
  });
  return { main, sub };
}
